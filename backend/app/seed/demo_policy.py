DEMO_POLICY_TEXT = """
Corporate Procurement Compliance Policy
Version 1.0 — Effective 2026-01-01

Section 1. Introduction
This policy governs all procurement activity across the organization, including
purchase orders, invoices, and goods receipts. It exists to ensure spending is
authorized, vendors are verified, and payments reconcile against what was
ordered and received.

Section 2. Scope
This policy applies to all departments and all vendors, regardless of order
value. Procurement staff and finance reviewers are jointly responsible for
enforcing the rules below before any invoice is approved for payment.

Section 3.1 Price Variance Tolerance
Price variances between the invoiced unit price and the purchase order unit
price exceeding 5% of the purchase order value require documented
justification from the requesting department before the invoice may be
approved. Variances within 5% are considered acceptable and require no
further action.

Section 3.2 Quantity Reconciliation
Invoice quantities must not exceed the quantities stated on the corresponding
purchase order or goods receipt note. Any excess quantity billed by a vendor
must be rejected or corrected before payment is released.

Section 4.1 Approval Thresholds
Purchases with a total value above ₹10,00,000 require VP-level approval prior
to payment. Purchases below this threshold may be approved at the
departmental level.

Section 4.2 Goods Receipt Requirement
Payment against any invoice requires a corresponding goods receipt
confirmation on file. Invoices lacking a linked goods receipt note must be
held pending confirmation of delivery.

Section 5.1 Vendor Identity Verification
The vendor name on an invoice must match the vendor name on the corresponding
purchase order exactly. Any mismatch must be investigated as a potential
billing error or unauthorized substitution before payment.

Section 5.2 Duplicate Invoice Detection
Duplicate invoices from the same vendor, identified by a repeated invoice
number for the same vendor, must be flagged and withheld from payment
pending manual verification that the invoice has not already been paid.

Section 6.1 Cumulative Project Spending Cap
Cumulative spending against a single project code must not exceed
₹25,00,000. Any purchase that would cause a project's cumulative spend to
exceed this cap requires additional review before approval.

Section 6.2 Vendor Spending Velocity
Cumulative spending with a single vendor exceeding ₹5,00,000 within any
rolling 30-day window requires review by the procurement committee,
regardless of whether individual purchase orders were each within normal
approval thresholds.

Section 7.1 Tax Reconciliation
Tax amounts stated on an invoice must reconcile with the applicable rate
applied to the line item subtotal. Invoices where the stated tax does not
match the expected calculation must be flagged for correction before
payment.

Section 8.3 Anti-Splitting Rule
Split orders placed with the same vendor within a 7-day window are
prohibited when their combined value exceeds ₹2,00,000. Splitting a single
procurement need into multiple smaller purchase orders to avoid approval
thresholds is a policy violation regardless of each individual order's
value.

Section 9.2 Vendor Performance Review
Vendor performance ratings below "Satisfactory" for two consecutive
quarters shall trigger a mandatory vendor performance review and may result
in suspension of future purchase orders pending remediation.
"""
